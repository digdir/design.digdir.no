const SLUG_PATTERN = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/;
const ILLUSTRATION_FILE = /\.(svg|png|webp|jpe?g)$/i;
const HEX_COLOR = /^#(?:[0-9a-f]{3}|[0-9a-f]{6})$/i;
const ANY_HEX_COLOR = /#(?:[0-9a-f]{3}|[0-9a-f]{6})\b/gi;
const COLOR_ATTRIBUTES = [
  'fill',
  'stroke',
  'stop-color',
  'flood-color',
  'lighting-color',
];
/** Keep full, lower-case-insensitive hex values so palette lookups are exact. */
const CONVERT_COLORS = {
  currentColor: false,
  names2hex: true,
  rgb2hex: true,
  shorthex: false,
  shortname: false,
};
/** Props already used by the generated component, so slots can't take them. */
const RESERVED_PROPS = new Set([
  'title',
  'titleId',
  'style',
  'ref',
  'key',
  'children',
]);

const toPascalCase = (slug: string) =>
  slug
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');

const toCamelCase = (slug: string) => {
  const pascal = toPascalCase(slug);
  return pascal.charAt(0).toLowerCase() + pascal.slice(1);
};

/** "Former og figurer" → "former-og-figurer" (æøå folded to ASCII). */
const slugify = (text: string) =>
  text
    .toLowerCase()
    .replace(/æ/g, 'ae')
    .replace(/ø/g, 'o')
    .replace(/å/g, 'a')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

const readJson = <T>(file: string): T =>
  JSON.parse(fs.readFileSync(file, 'utf8')) as T;

const listDirectories = (dir: string) =>
  fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();

/** Expand `#abc` to `#aabbcc` and lower-case, so palette lookups are stable. */
const normalizeHex = (hex: string) => {
  const value = hex.toLowerCase();
  if (value.length === 4) {
    return `#${value[1]}${value[1]}${value[2]}${value[2]}${value[3]}${value[3]}`;
  }
  return value;
};

/** The profile's palette, or null when it has no `colors.json`. */
const readPalette = (profile: string): IllustrationColor[] | null => {
  const file = path.join(sourceDir, profile, 'colors.json');
  if (!fs.existsSync(file)) return null;

  const palette = readJson<Palette>(file);

  return Object.entries(palette).map(([name, definition]) => {
    if (!SLUG_PATTERN.test(name)) {
      throw new Error(
        `Colour "${name}" in ${profile}/colors.json must be kebab-case (a-z, 0-9, -).`,
      );
    }
    for (const mode of ['light', 'dark'] as const) {
      if (!/^#[0-9a-f]{6}$/i.test(definition?.[mode] ?? '')) {
        throw new Error(
          `Colour "${name}" in ${profile}/colors.json needs a 6-digit hex "${mode}" value.`,
        );
      }
    }
    return {
      name,
      label: definition.label ?? name,
      variable: `${VARIABLE_PREFIX}-${profile}-${name}`,
      light: normalizeHex(definition.light),
      dark: normalizeHex(definition.dark),
    };
  });
};

const readMeta = (dir: string): Meta => {
  const file = path.join(dir, 'meta.json');
  if (!fs.existsSync(file)) {
    throw new Error(`Missing ${path.relative(packageRoot, file)}`);
  }

  const meta = readJson<Meta>(file);
  const relative = path.relative(packageRoot, file);

  if (typeof meta.title !== 'string' || meta.title.trim() === '') {
    throw new Error(`${relative}: "title" must be a non-empty string.`);
  }
  if (
    !Array.isArray(meta.tags) ||
    meta.tags.some((tag) => typeof tag !== 'string' || tag.trim() === '')
  ) {
    throw new Error(`${relative}: "tags" must be an array of strings.`);
  }
  if (meta.description !== undefined && typeof meta.description !== 'string') {
    throw new Error(`${relative}: "description" must be a string.`);
  }
  if (
    meta.project !== undefined &&
    (!Array.isArray(meta.project) ||
      meta.project.length === 0 ||
      meta.project.some(
        (project) => typeof project !== 'string' || project.trim() === '',
      ))
  ) {
    throw new Error(
      `${relative}: "project" must be a non-empty array of strings, e.g. ["eIDAS"].`,
    );
  }

  return meta;
};

/** The folder's one image file: an `.svg` or a raster `.png`/`.webp`/`.jpg`. */
const findIllustrationFile = (dir: string) => {
  const files = fs
    .readdirSync(dir)
    .filter((file) => ILLUSTRATION_FILE.test(file));
  const relative = path.relative(packageRoot, dir);

  if (files.length === 0) {
    throw new Error(`${relative}: no .svg, .png, .webp or .jpg file found.`);
  }
  if (files.length > 1) {
    throw new Error(
      `${relative}: expected exactly one image file, found ${files.join(', ')}.`,
    );
  }
  return path.join(dir, files[0]);
};

const rasterFormat = (file: string): RasterIllustrationMeta['format'] => {
  const extension = path.extname(file).slice(1).toLowerCase();
  return extension === 'jpeg' ? 'jpg' : (extension as 'png' | 'webp' | 'jpg');
};

/** Width and height from a PNG's IHDR chunk; 0×0 for other formats. */
const rasterSize = (file: string) => {
  const header = fs.readFileSync(file).subarray(0, 24);
  const isPng = header.readUInt32BE(0) === 0x89504e47;
  return isPng
    ? { width: header.readUInt32BE(16), height: header.readUInt32BE(20) }
    : { width: 0, height: 0 };
};

