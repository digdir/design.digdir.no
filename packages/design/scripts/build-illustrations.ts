const SLOT_MARKER = /^(.*?)\s*\[([^\]]*)\]\s*(?:\{([^}]*)\})?\s*$/;
const GROUP_MARKER = /\{[^}]*\}\s*$/;
const NO_EDIT_MARKER = /\[\s*no-edit\s*\]\s*$/i;

/**
 * Parse `Former [red,yellow] {Farger}` →
 * { label: 'Former', colors: [...], group: 'Farger' }.
 */
const parseSlotMarker = (
  layerName: string,
  colors: IllustrationColor[],
  context: string,
) => {
  const match = layerName.match(SLOT_MARKER);
  if (!match) {
    if (GROUP_MARKER.test(layerName)) {
      throw new Error(
        `${context}: layer "${layerName}" has a {group} but no [colour,…] list before it.`,
      );
    }
    return null;
  }

  const label = match[1].trim();
  const group = match[3]?.trim();
  const list = match[2]
    .split(',')
    .map((item) => item.trim().toLowerCase())
    .filter(Boolean);

  if (!label) {
    throw new Error(
      `${context}: layer "${layerName}" has no name before [...].`,
    );
  }
  if (group === '') {
    throw new Error(
      `${context}: layer "${layerName}" has an empty {group}. Name it, e.g. {Farger}, or remove the braces.`,
    );
  }
  if (list.length === 0) {
    throw new Error(
      `${context}: layer "${layerName}" has an empty colour list. Remove the brackets to keep the colour fixed.`,
    );
  }
  const known = new Set(colors.map((color) => color.name));
  for (const color of list) {
    if (!known.has(color)) {
      throw new Error(
        `${context}: layer "${layerName}" lists unknown colour "${color}". Use one of: ${[...known].join(', ')}.`,
      );
    }
  }
  return { label, colors: [...new Set(list)], group };
};

/** Slug and React prop for a slot or group name, checked for clashes. */
const toPropName = (label: string, layerName: string, context: string) => {
  const name = slugify(label);
  if (!SLUG_PATTERN.test(name)) {
    throw new Error(
      `${context}: layer "${layerName}" needs a name starting with a letter.`,
    );
  }
  const prop = toCamelCase(name);
  if (RESERVED_PROPS.has(prop)) {
    throw new Error(
      `${context}: name "${label}" clashes with the "${prop}" prop – pick another name.`,
    );
  }
  return { name, prop };
};

/**
 * Register the slot for a layer marked `Name [colour,…]`, or return undefined
 * for ordinary layers. Layers sharing a name share one slot. A `{Group}`
 * marker is recorded in `groupLabels` (slug → label).
 */
const registerSlot = (
  layerName: string,
  slots: Map<string, IllustrationSlot>,
  groupLabels: Map<string, string>,
  colors: IllustrationColor[],
  profile: string,
  name: string,
) => {
  const context = `${profile}/${name}`;
  const marker = parseSlotMarker(layerName, colors, context);
  if (!marker) return undefined;

  const { name: slotName, prop } = toPropName(marker.label, layerName, context);
  const group =
    marker.group && toPropName(marker.group, layerName, context).name;
  if (group && marker.group) groupLabels.set(group, marker.group);

  const existing = slots.get(slotName);
  if (existing) {
    if (
      existing.colors.join() !== marker.colors.join() ||
      existing.group !== group
    ) {
      throw new Error(
        `${context}: layers named "${marker.label}" list different colours or groups. Layers with the same name share one slot and must agree.`,
      );
    }
    return existing;
  }

  const slot: IllustrationSlot = {
    name: slotName,
    label: marker.label,
    prop,
    variable: `${VARIABLE_PREFIX}-${profile}-${name}-${slotName}`,
    default: '',
    colors: marker.colors,
    ...(group && { group }),
  };
  slots.set(slotName, slot);
  return slot;
};

/**
 * svgo plugin that swaps palette colours for CSS variables and registers
 * colour slots from `data-name` markers. Inside a slotted element, shapes
 * drawn in the slot's colour get the slot variable (falling back to the
 * palette variable); everything else gets the palette variable. Inside a
 * `[no-edit]` element nothing is swapped, and the colours met are added to
 * `fixedHexes` so they are not reported as missing from the palette.
 */
const themeColorsPlugin = (
  byHex: Map<string, IllustrationColor>,
  colors: IllustrationColor[],
  slots: Map<string, IllustrationSlot>,
  groupLabels: Map<string, string>,
  fixedHexes: Set<string>,
  profile: string,
  name: string,
): CustomPlugin => ({
  name: 'designThemeColors',
  fn: () => {
    const stack: { node: XastElement; slot: IllustrationSlot }[] = [];
    let fixedRoot: XastElement | undefined;

    return {
      element: {
        enter: (node: XastElement) => {
          const layerName = node.attributes['data-name'];
          if (!fixedRoot && layerName && NO_EDIT_MARKER.test(layerName)) {
            fixedRoot = node;
          }
          if (fixedRoot) {
            for (const attribute of COLOR_ATTRIBUTES) {
              const value = node.attributes[attribute];
              if (value && HEX_COLOR.test(value)) {
                fixedHexes.add(normalizeHex(value));
              }
            }
            return;
          }

          const slot =
            layerName &&
            registerSlot(layerName, slots, groupLabels, colors, profile, name);
          if (slot) stack.push({ node, slot });
          const active = stack.at(-1)?.slot;

          for (const attribute of COLOR_ATTRIBUTES) {
            const value = node.attributes[attribute];
            if (!value || !HEX_COLOR.test(value)) continue;
            const color = byHex.get(normalizeHex(value));
            if (!color) continue; // reported after optimisation
            const paletteVar = `var(${color.variable}, ${color.light})`;

            // The first palette colour met inside a slot (the marked element
            // itself comes first) is the colour that slot swaps.
            if (active && !active.default) active.default = color.name;

            node.attributes[attribute] =
              active && active.default === color.name
                ? `var(${active.variable}, ${paletteVar})`
                : paletteVar;
          }
        },
        exit: (node: XastElement) => {
          if (fixedRoot === node) fixedRoot = undefined;
          if (stack.at(-1)?.node === node) stack.pop();
        },
      },
    };
  },
});

/**
 * Optimise the SVG and swap palette colours for CSS variables. Any colour that
 * is not in the palette is left as-is and reported, so it can be added to
 * `colors.json` (or fixed in the SVG).
 */
const processSvg = (
  svg: string,
  profile: string,
  name: string,
  colors: IllustrationColor[],
  fixedColors: boolean,
) => {
  const context = `${profile}/${name}`;
  const byHex = new Map(colors.map((color) => [color.light, color]));
  const slots = new Map<string, IllustrationSlot>();
  const groupLabels = new Map<string, string>();
  const fixedHexes = new Set<string>();

  // Pass 1: get every colour onto an attribute and swap it for a variable,
  // before preset-default merges paths, hoists attributes or drops data-name.
  const themed = optimize(svg, {
    multipass: false,
    plugins: [
      'mergeStyles',
      { name: 'inlineStyles', params: { onlyMatchedOnce: false } },
      'convertStyleToAttrs',
      { name: 'convertColors', params: CONVERT_COLORS },
      themeColorsPlugin(
        byHex,
        colors,
        slots,
        groupLabels,
        fixedHexes,
        profile,
        name,
      ),
    ],
  }).data;

  // Pass 2: the usual optimisation.
  const optimized = optimize(themed, {
    multipass: true,
    plugins: [
      {
        name: 'preset-default',
        params: { overrides: { convertColors: CONVERT_COLORS } },
      },
      // Several illustrations may be inlined on one page – keep ids unique.
      { name: 'prefixIds', params: { prefix: name } },
      // Drop the root width/height so the container decides the size, and
      // Illustrator's data-name attributes (the viewBox is kept – svgo 4 no
      // longer removes it by default).
      {
        name: 'removeAttrs',
        params: { attrs: ['svg:(width|height)', 'data-name'] },
      },
    ],
  }).data;

  // Anything still hard-coded was not in the palette (or sat in a style),
  // unless it was kept on purpose in a `[no-edit]` layer.
  const unknown = new Set(
    (optimized.match(ANY_HEX_COLOR) ?? []).filter(
      (hex) =>
        !byHex.has(normalizeHex(hex)) && !fixedHexes.has(normalizeHex(hex)),
    ),
  );
  if (unknown.size > 0 && !fixedColors) {
    console.warn(
      `  ⚠ ${context}: colour(s) ${[...unknown].join(', ')} are not in ${profile}/colors.json and will not follow the colour scheme.`,
    );
  }

  for (const slot of slots.values()) {
    if (!slot.default) {
      throw new Error(
        `${context}: layer "${slot.label}" is marked as a colour slot but no palette colour was found in it.`,
      );
    }
    if (!slot.colors.includes(slot.default)) {
      console.warn(
        `  ⚠ ${context}: layer "${slot.label}" is drawn in "${slot.default}" but does not list it – adding it.`,
      );
      slot.colors.unshift(slot.default);
    }
  }

  const slotList = [...slots.values()];
  return {
    svg: optimized,
    slots: slotList,
    groups: buildGroups(slotList, groupLabels, colors, context),
  };
};

/**
 * Groups from the slots' `{Group}` markers. Each slot in a group must have
 * one colour per family, cover the same families as the others and be drawn
 * in the same family, so picking a family always has one answer per slot.
 */
const buildGroups = (
  slots: IllustrationSlot[],
  groupLabels: Map<string, string>,
  colors: IllustrationColor[],
  context: string,
): IllustrationSlotGroup[] => {
  // Families in palette order, so every group lists them the same way.
  const paletteOrder = [
    ...new Set(colors.map((color) => colorFamily(color.name))),
  ];

  const ungroupedProps = new Set(
    slots.filter((slot) => !slot.group).map((slot) => slot.prop),
  );

  return [...groupLabels].map(([name, label]) => {
    const members = slots.filter((slot) => slot.group === name);
    const familiesOf = (slot: IllustrationSlot) => {
      const families = slot.colors.map(colorFamily);
      if (new Set(families).size !== families.length) {
        throw new Error(
          `${context}: layer "${slot.label}" in group "${label}" lists more than one colour from the same family (${slot.colors.join(', ')}).`,
        );
      }
      return families;
    };

    const [first, ...rest] = members;
    const families = familiesOf(first);
    const defaultFamily = colorFamily(first.default);
    for (const slot of rest) {
      const own = familiesOf(slot);
      if (
        own.length !== families.length ||
        own.some((family) => !families.includes(family))
      ) {
        throw new Error(
          `${context}: layers "${first.label}" (${families.join(', ')}) and "${slot.label}" (${own.join(', ')}) in group "${label}" must cover the same colour families.`,
        );
      }
      if (colorFamily(slot.default) !== defaultFamily) {
        throw new Error(
          `${context}: layers "${first.label}" and "${slot.label}" in group "${label}" are drawn in different colour families (${first.default}, ${slot.default}).`,
        );
      }
    }

    const prop = toCamelCase(name);
    if (ungroupedProps.has(prop)) {
      throw new Error(
        `${context}: group "${label}" has the same name as a layer – pick another name.`,
      );
    }
    return {
      name,
      label,
      prop,
      default: defaultFamily,
      colors: paletteOrder.filter((family) => families.includes(family)),
    };
  });
};

