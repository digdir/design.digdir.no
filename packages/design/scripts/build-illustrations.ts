/**
 * Generates the illustration library from `illustrations/<profile>/<name>/`.
 *
 * Each profile folder has one folder per illustration containing exactly one
 * image – an `.svg`, or a raster `.png`/`.webp`/`.jpg` – and a `meta.json`
 * (see `meta.schema.json`), and optionally a
 * `colors.json` (the palette used by its illustrations, with light and dark
 * values). Without `colors.json` the illustrations keep their drawn colours:
 * no dark mode and no colour slots.
 *
 * For every profile this writes, under `generated/illustrations/<profile>/`:
 *   - `react/<Name>.tsx` + `react/index.ts`  React components
 *   - `svg.ts`                                framework-agnostic SVG strings
 *   - `meta.ts`                               titles, tags, colours, slots
 * and, under `dist/illustrations/`, a `<profile>.css` with the colour
 * variables plus an `index.css` combining every profile. Raster images are
 * copied as-is to `dist/illustrations/<profile>/`, and `images.ts` exports
 * each one's URL through an asset import (`import url from './file.png'`), so
 * bundlers emit the file and return its URL – also when server rendering –
 * instead of inlining base64 in the JS. The shared types and
 * helpers in `src/illustrations/index.ts` are copied to
 * `generated/illustrations/index.ts` with the profile list and loaders added.
 *
 * The modules are published per profile, as
 * `@digdir/digdir-design/<profile>/illustrations/{react,svg,meta,images,css}`.
 * Profiles in `profiles/` without an illustration folder get empty modules,
 * so every profile has the same entry points.
 *
 * Colours: hard-coded palette colours are replaced with
 * `var(--design-illustration-<profile>-<colour>, <light hex>)`, so the SVGs
 * render correctly without the CSS and switch to the dark palette when the
 * CSS is loaded and `data-color-scheme="dark"` is set.
 *
 * Colour slots: a layer named `Former [red,yellow]` in Illustrator marks
 * the shape(s) as recolourable to the listed palette colours. The build reads
 * the marker from the exported `data-name` attribute (Illustrator flattens the
 * brackets in `id`), gives the slot its own variable that falls back to the
 * drawn colour, adds a typed prop to the React component and lists the slot
 * in `meta.ts`. Layers without a `[...]` list are never recoloured.
 *
 * Slot groups: slots marked `Flammer [red-40,yellow-40] {Farger}` and
 * `Sekk [red,yellow] {Farger}` change colour together. The group gets one
 * prop (`farger`), set to a colour family (`red`), and each slot takes its
 * own colour in that family (`red-40`, `red`). A family is the colour name
 * without its `-NN` step. Every slot in a group must cover the same families
 * and be drawn in the same one.
 *
 * Fixed parts: a layer named `Bilde [no-edit]` keeps its drawn colours in
 * both light and dark mode – palette colours in it are not swapped for
 * variables. On a group it applies to everything in the group.
 *
 * Run with `node scripts/build-illustrations.ts` (Node ≥ 22.18 strips types),
 * then compile `generated/` with `tsc -p tsconfig.build.json`.
 */
