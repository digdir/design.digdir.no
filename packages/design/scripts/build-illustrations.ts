const buildProfile = async (profile: string) => {
  const profileDir = path.join(sourceDir, profile);
  const outDir = path.join(generatedDir, profile);
  const reactDir = path.join(outDir, 'react');
  fs.mkdirSync(reactDir, { recursive: true });

  const palette = readPalette(profile);
  const darkMode = palette !== null;
  const colors = palette ?? [];
  const illustrations: VectorIllustration[] = [];
  const rasters: RasterIllustration[] = [];

  const hasSource = fs.existsSync(profileDir);

  for (const name of hasSource ? listDirectories(profileDir) : []) {
    if (!SLUG_PATTERN.test(name)) {
      throw new Error(
        `Illustration folder "${profile}/${name}" must be kebab-case (a-z, 0-9, -) and start with a letter.`,
      );
    }

    const dir = path.join(profileDir, name);
    const meta = readMeta(dir);
    const file = findIllustrationFile(dir);
    const exportName = toCamelCase(name);

    if (!file.endsWith('.svg')) {
      const format = rasterFormat(file);
      rasters.push({
        format,
        name,
        exportName,
        title: meta.title,
        description: meta.description,
        tags: meta.tags,
        project: meta.project,
        file: `${name}.${format}`,
        ...rasterSize(file),
        source: file,
      });
      continue;
    }

    const rawSvg = fs.readFileSync(file, 'utf8');
    const { svg, slots, groups } = processSvg(
      rawSvg,
      profile,
      name,
      colors,
      !darkMode,
    );
    const componentName = toPascalCase(name);

    fs.writeFileSync(
      path.join(reactDir, `${componentName}.tsx`),
      await buildReactComponent(svg, componentName, profile, slots, groups),
    );

    illustrations.push({
      format: 'svg',
      name,
      componentName,
      exportName,
      title: meta.title,
      description: meta.description,
      tags: meta.tags,
      project: meta.project,
      viewBox: svg.match(/viewBox=["']([^"']+)["']/)?.[1],
      slots,
      groups,
      svg,
    });
  }

  // Raster files sit next to the compiled `images.js` that points at them.
  fs.mkdirSync(path.join(distDir, profile), { recursive: true });
  for (const item of rasters) {
    fs.copyFileSync(item.source, path.join(distDir, profile, item.file));
  }
  fs.writeFileSync(
    path.join(outDir, 'images.ts'),
    [
      GENERATED_HEADER,
      '// URLs of the raster illustrations. Bundlers (Vite, webpack, Parcel)',
      '// emit each imported file as an asset and give back its URL.',
      '',
      ...rasters.map(
        (item) => `import ${item.exportName}Url from './${item.file}';`,
      ),
      '',
      ...rasters.map(
        (item) =>
          `export const ${item.exportName}: string = ${item.exportName}Url;`,
      ),
      ...(rasters.length === 0 ? ['export {};'] : []),
      '',
    ].join('\n'),
  );

  if (illustrations.length === 0 && rasters.length === 0) {
    if (hasSource) console.warn(`  ⚠ ${profile}: no illustrations found.`);
  }

  fs.writeFileSync(
    path.join(reactDir, 'index.ts'),
    [
      GENERATED_HEADER,
      ...illustrations.map(
        (item) =>
          `export { default as ${item.componentName} } from './${item.componentName}.js';`,
      ),
      ...(illustrations.length === 0 ? ['export {};'] : []),
      '',
    ].join('\n'),
  );

  fs.writeFileSync(
    path.join(outDir, 'svg.ts'),
    [
      GENERATED_HEADER,
      `// Framework-agnostic SVG strings. Load \`@digdir/digdir-design/${profile}/illustrations/css\``,
      '// for dark mode support.',
      '',
      ...illustrations.map(
        (item) =>
          `export const ${item.exportName} = ${JSON.stringify(item.svg)};`,
      ),
      // Keep the file a module when the profile has no SVG illustrations.
      ...(illustrations.length === 0 ? ['export {};'] : []),
      '',
    ].join('\n'),
  );

  const metaEntries = [
    ...illustrations.map(({ svg: _svg, ...rest }) => rest),
    ...rasters.map(({ source: _source, ...rest }) => rest),
  ].sort((a, b) => a.name.localeCompare(b.name));
  fs.writeFileSync(
    path.join(outDir, 'meta.ts'),
    [
      GENERATED_HEADER,
      "import type { IllustrationColor, IllustrationMeta } from '../index.js';",
      '',
      `export const profile = ${JSON.stringify(profile)};`,
      '',
      `export const darkMode = ${darkMode};`,
      '',
      `export const colors: IllustrationColor[] = ${JSON.stringify(colors, null, 2)};`,
      '',
      `export const illustrations: IllustrationMeta[] = ${JSON.stringify(metaEntries, null, 2)};`,
      '',
    ].join('\n'),
  );

  const declarations = (mode: 'light' | 'dark') =>
    colors.map((color) => `  ${color.variable}: ${color[mode]};`).join('\n');
  const css = !darkMode
    ? [
        `/* Generated by scripts/build-illustrations.ts – do not edit. */`,
        `/* The "${profile}" illustrations use fixed colours – nothing to load. */`,
        '',
      ].join('\n')
    : [
        `/* Generated by scripts/build-illustrations.ts – do not edit. */`,
        `/* Colours for the "${profile}" illustrations in @digdir/digdir-design. */`,
        ':root,',
        `[data-color-scheme='light'] {`,
        declarations('light'),
        '}',
        '',
        `[data-color-scheme='dark'] {`,
        declarations('dark'),
        '}',
        '',
        '@media (prefers-color-scheme: dark) {',
        `  [data-color-scheme='auto'] {`,
        declarations('dark').replace(/^/gm, '  '),
        '  }',
        '}',
        '',
        '@media (prefers-color-scheme: light) {',
        `  [data-color-scheme='auto'] {`,
        declarations('light').replace(/^/gm, '  '),
        '  }',
        '}',
        '',
      ].join('\n');
  fs.writeFileSync(path.join(distDir, `${profile}.css`), css);

  const slotCount = illustrations.reduce(
    (sum, item) => sum + item.slots.length,
    0,
  );
  console.log(
    `  ✓ ${profile}: ${illustrations.length} SVG(s), ${slotCount} colour slot(s), ${rasters.length} image(s)`,
  );
  return css;
};

/** `@digdir/digdir-design/illustrations`: the checked-in runtime plus generated data. */
const writeIndex = (profiles: string[]) => {
  const runtime = fs
    .readFileSync(runtimeSource, 'utf8')
    .replace(
      /^\/\*\*[\s\S]*?\*\/\n/,
      `${GENERATED_HEADER}\n// Source: src/illustrations/index.ts\n`,
    );

  const loaders = profiles.map(
    (profile) =>
      `  ${JSON.stringify(profile)}: () =>\n    loadIllustrationLibrary(import('./${profile}/meta.js'), import('./${profile}/svg.js'), import('./${profile}/images.js')),`,
  );

  // Lets tsc compile the asset imports in each profile's `images.ts`.
  fs.writeFileSync(
    path.join(generatedDir, 'assets.d.ts'),
    [
      GENERATED_HEADER,
      ...['png', 'webp', 'jpg'].map(
        (extension) =>
          `declare module '*.${extension}' {\n  const url: string;\n  export default url;\n}`,
      ),
      '',
    ].join('\n'),
  );

  fs.writeFileSync(
    path.join(generatedDir, 'index.ts'),
    [
      runtime,
      '/** Profiles that ship illustrations. */',
      `export const illustrationProfiles = ${JSON.stringify(profiles)} as const;`,
      '',
      'export type IllustrationProfile = (typeof illustrationProfiles)[number];',
      '',
      '/**',
      " * Lazy loader per profile. Each loads that profile's metadata, SVG",
      ' * strings and image URLs on demand, so bundlers can split them per profile.',
      ' */',
      'export const illustrationLoaders: Record<',
      '  IllustrationProfile,',
      '  () => Promise<IllustrationLibrary>',
      '> = {',
      ...loaders,
      '};',
      '',
    ].join('\n'),
  );
};

const build = async () => {
  fs.rmSync(generatedDir, { recursive: true, force: true });
  fs.mkdirSync(generatedDir, { recursive: true });
  fs.mkdirSync(distDir, { recursive: true });

  // Profiles with illustrations, plus the rest of the package's profiles –
  // those get empty modules.
  const withIllustrations = listDirectories(sourceDir);
  const profiles = [
    ...new Set([
      ...withIllustrations,
      ...listDirectories(profilesDir).filter(
        (profile) => profile !== SHARED_PROFILE,
      ),
    ]),
  ].sort();
  console.log(`Building illustrations for ${profiles.length} profile(s)…`);

  const cssChunks: string[] = [];
  for (const profile of profiles) {
    cssChunks.push(await buildProfile(profile));
  }
  fs.writeFileSync(path.join(distDir, 'index.css'), cssChunks.join('\n'));

  writeIndex(withIllustrations);
};

build().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
