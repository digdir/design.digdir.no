/**
 * SVGR renders only an inner `Svg` function (props + ref, no export); the
 * exported component is written by us below, so slot props never depend on
 * SVGR's output formatting.
 */
const buildReactComponent = async (
  svg: string,
  componentName: string,
  profile: string,
  slots: IllustrationSlot[],
  groups: IllustrationSlotGroup[],
) => {
  const inner = await transform(
    svg,
    {
      plugins: ['@svgr/plugin-jsx'],
      typescript: true,
      jsxRuntime: 'automatic',
      ref: true,
      titleProp: true,
      dimensions: false,
      expandProps: 'end',
      template: (variables, { tpl }) => tpl`
        ${variables.imports};
        ${variables.interfaces};
        const ${variables.componentName} = (${variables.props}) => (
          ${variables.jsx}
        );
      `,
    },
    { componentName: 'Svg' },
  );

  if (slots.length === 0) {
    return [
      GENERATED_HEADER,
      inner,
      `const ${componentName} = forwardRef(Svg);`,
      `export default ${componentName};`,
      '',
    ].join('\n');
  }

  const ungrouped = slots.filter((slot) => !slot.group);
  const union = (values: string[]) =>
    values.map((value) => `'${value}'`).join(' | ');
  const slotProps = [
    ...ungrouped.map(
      (slot) =>
        `  /** Colour of "${slot.label}". Defaults to "${slot.default}". */\n  ${slot.prop}?: ${union(slot.colors)};`,
    ),
    ...groups.map(
      (group) =>
        `  /** Colour family of "${group.label}" (${slots
          .filter((slot) => slot.group === group.name)
          .map((slot) => slot.label)
          .join(
            ', ',
          )}). Defaults to "${group.default}". */\n  ${group.prop}?: ${union(group.colors)};`,
    ),
  ].join('\n');
  // A grouped slot maps its group's family to its own colour in that family.
  const slotValue = (slot: IllustrationSlot) => {
    const group = groups.find((candidate) => candidate.name === slot.group);
    if (!group) return slot.prop;
    const byFamily = group.colors
      .map((family) => `'${family}': '${slotColorInFamily(slot, family)}'`)
      .join(', ');
    return `${group.prop} && { ${byFamily} }[${group.prop}]`;
  };
  const slotVariables = slots
    .map((slot) => `'${slot.variable}': ${slotValue(slot)}`)
    .join(', ');
  const destructured = [...ungrouped, ...groups]
    .map((entry) => entry.prop)
    .join(', ');

  return [
    GENERATED_HEADER,
    "import { applySlots } from '../../index.js';",
    inner,
    'interface SlotProps {',
    slotProps,
    '}',
    `const ${componentName} = forwardRef<SVGSVGElement, Parameters<typeof Svg>[0] & SlotProps>(`,
    `  ({ ${destructured}, style, ...props }, ref) =>`,
    `    Svg({ ...props, style: applySlots(style, '${VARIABLE_PREFIX}-${profile}', { ${slotVariables} }) }, ref),`,
    ');',
    `export default ${componentName};`,
    '',
  ].join('\n');
};

