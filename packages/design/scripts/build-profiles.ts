import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import autoprefixer from 'autoprefixer';
import cssnano from 'cssnano';
import postcss, { type Plugin } from 'postcss';
import postcssNesting from 'postcss-nesting';
import {
  buildExports,
  listProfiles,
  MAIN_PROFILE,
  PUBLISHED_PROFILES,
  packageRoot,
  profilesDir,
  SHARED_PROFILE,
} from './exports.ts';

const distDir = path.join(packageRoot, 'dist');
/** Themes built by `pnpm tokens` at the repository root. */
const themesDir = path.resolve(packageRoot, '..', '..', 'design-tokens-build');

/** Scopes compiled from `index.<scope>.ts`. */
const CODE_SCOPES = ['react', 'web'];
/** `dist/` folders used by other parts of the package. */
const RESERVED_PROFILES = new Set(['illustrations']);
/** `dist/<profile>/` folders written by this script. */
const RESERVED_COMPONENTS = new Set(['css', 'theme']);
/** Stylesheets written by this script. */
const RESERVED_STYLESHEETS = new Set(['index.css', 'components.css']);
const SLUG_PATTERN = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/;
const GENERATED = '/* Generated by scripts/build-profiles.ts - do not edit. */';

const packageJson = JSON.parse(
  fs.readFileSync(path.join(packageRoot, 'package.json'), 'utf8'),
) as {
  exports: Record<string, unknown>;
  dependencies: Record<string, string>;
};

const relative = (file: string) => path.relative(packageRoot, file);

const listDirectories = (dir: string) =>
  fs.existsSync(dir)
    ? fs
        .readdirSync(dir, { withFileTypes: true })
        .filter((entry) => entry.isDirectory())
        .map((entry) => entry.name)
        .sort()
    : [];

/**
 * Designsystemet's CSS, to put in front of each profile's components. It is
 * copied in at build time, so its version must be the one the React and web
 * components are pinned to.
 */
const readDesignsystemetCss = () => {
  const file = fileURLToPath(import.meta.resolve('@digdir/designsystemet-css'));
  // The entry is `<package>/dist/src/index.css`.
  const { version } = JSON.parse(
    fs.readFileSync(
      path.resolve(file, '..', '..', '..', 'package.json'),
      'utf8',
    ),
  ) as { version: string };

  for (const name of [
    '@digdir/designsystemet-react',
    '@digdir/designsystemet-web',
  ]) {
    if (packageJson.dependencies[name] !== version) {
      throw new Error(
        `@digdir/designsystemet-css is ${version}, but ${name} is "${packageJson.dependencies[name]}" in package.json. Pin all three to the same version.`,
      );
    }
  }

  return [fs.readFileSync(file, 'utf8').trimEnd()].join('\n');
};

/** The `.css` files in a profile's component folders, by file name. */
const listStylesheets = (profile: string) => {
  const stylesheets = new Map<string, string>();
  for (const component of listDirectories(path.join(profilesDir, profile))) {
    const dir = path.join(profilesDir, profile, component);
    for (const file of fs.readdirSync(dir).sort()) {
      if (!file.endsWith('.css')) continue;
      const existing = stylesheets.get(file);
      if (existing) {
        throw new Error(
          `"${file}" exists in both ${relative(existing)} and ${relative(dir)} - stylesheet names must be unique within a profile.`,
        );
      }
      if (RESERVED_STYLESHEETS.has(file)) {
        throw new Error(
          `${relative(path.join(dir, file))}: ${file} is generated - give the file another name.`,
        );
      }
      stylesheets.set(file, path.join(dir, file));
    }
  }
  return stylesheets;
};

const hasTheme = (theme: string) =>
  fs.existsSync(path.join(themesDir, `${theme}.css`));

/** The profile's theme names, the default first. */
const listThemes = (profile: string) => {
  const file = path.join(profilesDir, profile, 'themes.json');
  if (!fs.existsSync(file)) {
    return [hasTheme(profile) ? profile : MAIN_PROFILE];
  }

  const themes: unknown = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (
    !Array.isArray(themes) ||
    themes.length === 0 ||
    themes.some((theme) => typeof theme !== 'string')
  ) {
    throw new Error(
      `${relative(file)} must be a list of theme names, e.g. ["${profile}"].`,
    );
  }
  for (const theme of themes as string[]) {
    if (!hasTheme(theme)) {
      throw new Error(
        `${relative(file)}: there is no design-tokens-build/${theme}.css. Run \`pnpm tokens\` at the repository root, or fix the name.`,
      );
    }
    if (theme === 'index') {
      throw new Error(`${relative(file)}: a theme cannot be called "index".`);
    }
  }
  return themes as string[];
};

/**
 * PostCSS plugin that takes the layer order statements (`@layer a, b;`) out of
 * a stylesheet and adds them to `statements`, each one once. The build writes
 * them back at the very top of every file, so the order of the layers is set
 * before any of them is used – however many components repeat the statement,
 * and whatever the minifier does with the rest.
 */
const collectLayerOrder = (statements: Set<string>): Plugin => ({
  postcssPlugin: 'collect-layer-order',
  Once(root) {
    root.each((node) => {
      // A statement has no block; `@layer a { … }` does and stays put.
      if (node.type === 'atrule' && node.name === 'layer' && !node.nodes) {
        statements.add(`@layer ${node.params.replace(/\s*,\s*/g, ', ')};`);
        node.remove();
      }
    });
  },
});


const processCss = async (css: string, from: string) => {
  const statements = new Set<string>();
  const result = await postcss([
    postcssNesting(),
    autoprefixer(),
    collectLayerOrder(statements),
    cssnano({ preset: 'default' }),
  ]).process(css, { from, to: undefined, map: false });

  for (const warning of result.warnings()) {
    console.warn(`  ⚠ ${relative(from)}: ${warning.text}`);
  }
  return { layerOrder: [...statements].join('\n'), css: result.css.trim() };
};

const buildStylesheets = async (
  profile: string,
  designsystemetCss: string,
  sharedStylesheets: Map<string, string>,
) => {
  // The profile's own files win over shared files with the same name.
  const stylesheets = new Map([
    ...sharedStylesheets,
    ...listStylesheets(profile),
  ]);
  const outDir = path.join(distDir, profile, 'css');
  fs.mkdirSync(outDir, { recursive: true });

  // Each file starts with a note, then the layer order, then the styles.
  const write = (name: string, description: string, parts: string[]) =>
    fs.writeFileSync(
      path.join(outDir, name),
      `${[GENERATED, `/* ${description} */`, ...parts].filter(Boolean).join('\n')}\n`,
    );

  const names = [...stylesheets.keys()].sort();
  const sources: string[] = [];
  for (const name of names) {
    const source = stylesheets.get(name) as string;
    const css = fs.readFileSync(source, 'utf8');
    sources.push(css);

    const component = await processCss(css, source);
    write(name, `Built from ${relative(source)}.`, [
      component.layerOrder,
      component.css,
    ]);
  }

  // Combined rather than `@import`ed, so the files also work when they are
  // loaded straight from a `<link>` without a bundler.
  const components = await processCss(
    sources.join('\n'),
    path.join(profilesDir, profile, 'components.css'),
  );
  write(
    'components.css',
    `The "${profile}" profile's own components in @digdir/digdir-design. Needs Designsystemet's CSS – use index.css to get both.`,
    [components.layerOrder, components.css],
  );
  // Designsystemet's CSS is already built, and goes in as it is.
  write(
    'index.css',
    `Styles for the "${profile}" profile in @digdir/digdir-design: Designsystemet's CSS, then the profile's own components.`,
    [components.layerOrder, designsystemetCss, components.css],
  );

  return names.length;
};

const buildThemes = (profile: string) => {
  const themes = listThemes(profile);
  const outDir = path.join(distDir, profile, 'theme');
  fs.mkdirSync(outDir, { recursive: true });

  for (const theme of themes) {
    fs.copyFileSync(
      path.join(themesDir, `${theme}.css`),
      path.join(outDir, `${theme}.css`),
    );
  }
  fs.copyFileSync(
    path.join(themesDir, `${themes[0]}.css`),
    path.join(outDir, 'index.css'),
  );

  return themes;
};

const build = async () => {
  const profiles = listProfiles();
  const sharedStylesheets = listStylesheets(SHARED_PROFILE);
  const designsystemetCss = readDesignsystemetCss();
  const errors: string[] = [];

  if (JSON.stringify(packageJson.exports) !== JSON.stringify(buildExports())) {
    errors.push(
      '"exports" in package.json does not match the published profiles. Run `pnpm run exports`.',
    );
  }

  console.log(`Building components for ${profiles.length} profile(s)…`);

  for (const profile of profiles) {
    if (!SLUG_PATTERN.test(profile) || RESERVED_PROFILES.has(profile)) {
      errors.push(
        `Profile folder "${profile}" must be kebab-case (a-z, 0-9, -) and not one of: ${[...RESERVED_PROFILES].join(', ')}.`,
      );
      continue;
    }

    for (const scope of CODE_SCOPES) {
      if (
        !fs.existsSync(path.join(profilesDir, profile, `index.${scope}.ts`))
      ) {
        errors.push(`Missing profiles/${profile}/index.${scope}.ts.`);
      }
    }
    for (const component of listDirectories(path.join(profilesDir, profile))) {
      if (RESERVED_COMPONENTS.has(component)) {
        errors.push(
          `profiles/${profile}/${component}/ is a reserved name – give the component folder another name.`,
        );
      }
    }

    const stylesheets = await buildStylesheets(
      profile,
      designsystemetCss,
      sharedStylesheets,
    );
    const themes = buildThemes(profile);

    const borrowed =
      profile !== MAIN_PROFILE && themes[0] === MAIN_PROFILE
        ? ' (has none of its own)'
        : '';
    const unpublished = PUBLISHED_PROFILES.includes(profile)
      ? ''
      : ' – only the theme is exported';
    console.log(
      `  ✓ ${profile}: ${stylesheets} stylesheet(s), theme ${themes.join(', ')}${borrowed}${unpublished}`,
    );
  }

  if (errors.length > 0) {
    throw new Error(errors.map((error) => `  ✗ ${error}`).join('\n'));
  }
};

build().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
